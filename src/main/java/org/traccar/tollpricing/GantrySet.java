package org.traccar.tollpricing;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.locationtech.jts.geom.Envelope;
import org.locationtech.jts.index.strtree.STRtree;

import java.io.IOException;
import java.io.InputStream;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Date;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.NavigableMap;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * A flat-rate facility's toll points: every rate-card plaza with the clustered map locations that
 * charge it (generated by {@code build_cfx_plazas.py} / {@code build_istha_plazas.py}), joined to the
 * rate for the fleet's vehicle class and payment method on every card the facility publishes. Plazas
 * with no location are kept out of the index and listed, so a passage there is missed (estimate low),
 * never invented.
 *
 * <p>A facility may publish several cards (the Illinois Tollway reprices on 2027-01-01): each passage
 * is charged from the card in effect on the passage's local date in the facility's timezone. Every
 * card must list exactly the gantry file's plazas, so a reprice that adds or drops a plaza fails the
 * load instead of pricing silently from a stale map.
 */
public final class GantrySet {

    /**
     * One clustered map location of a plaza. A ramp point also carries its ramp's shape and the
     * nearby mainline's, as [lat, lon] lines; a mainline point carries neither.
     */
    public record Point(String facilityId, String plaza, double lat, double lon,
                        NavigableMap<LocalDate, BigDecimal> rates,
                        List<double[][]> rampLines, List<double[][]> mainlineLines) {
        public boolean isRamp() {
            return rampLines != null;
        }
    }

    /** A plaza's charge on a given day and the card it came from. */
    public record Rate(BigDecimal amount, String cardValidFrom) {
    }

    /**
     * A ramp point is indexed by its ramp shape's bounding box grown by this much, so a fix anywhere
     * within {@link PassageDetector#ON_RAMP_M} of the shape finds it, at any latitude.
     */
    static final double RAMP_MARGIN_M = 2 * PassageDetector.ON_RAMP_M;

    private final String facilityId;
    private final String currency;
    private final ZoneId zone;
    private final NavigableMap<LocalDate, String> cards = new TreeMap<>();
    private final String osmBase;
    private final List<Point> points = new ArrayList<>();
    private final List<String> unlocated = new ArrayList<>();
    private final List<String> excludedRamps = new ArrayList<>();
    private final List<String> rampsWithoutGeometry = new ArrayList<>();
    private final STRtree index = new STRtree();
    private final STRtree rampIndex = new STRtree();
    private final Envelope extent = new Envelope();

    private GantrySet(String facilityId, String currency, ZoneId zone, String osmBase) {
        this.facilityId = facilityId;
        this.currency = currency;
        this.zone = zone;
        this.osmBase = osmBase;
    }

    /**
     * @param cardStreams   every card the facility publishes, in any order
     * @param paymentColumn card column for the payment method, e.g. {@code "pay_by_plate"}
     * @param vehicleColumn card column for the vehicle class, e.g. {@code "2_axle"}
     * @param includeRamps  whether ramp plazas are priced. Ramps are never detected by distance to the
     *                      booth (half of CFX's lie within 50 m of the mainline); a ramp is charged only
     *                      when a fix lies on its shape and clear of the mainline ({@link PassageDetector}).
     *                      A ramp without both shapes is left unpriced and listed.
     * @param zone          the facility's timezone: a card takes effect at local midnight
     */
    public static GantrySet load(String facilityId, List<InputStream> cardStreams, InputStream gantries,
                                 String paymentColumn, String vehicleColumn, boolean includeRamps, ZoneId zone)
            throws IOException {
        ObjectMapper mapper = new ObjectMapper();
        JsonNode g = mapper.readTree(gantries);
        Set<String> gantryKeys = new TreeSet<>();
        for (JsonNode p : g.path("plazas")) {
            gantryKeys.add(p.path("road").asText() + "|" + p.path("name").asText());
        }
        String currency = null;
        Map<String, TreeMap<LocalDate, BigDecimal>> rates = new HashMap<>();
        NavigableMap<LocalDate, String> validFrom = new TreeMap<>();
        for (InputStream stream : cardStreams) {
            JsonNode c = mapper.readTree(stream);
            String from = c.path("valid_from").asText();
            if (!"flat".equals(c.path("rate_model_type").asText())) {
                throw new IOException(facilityId + ": card " + from + " is not a flat card");
            }
            if (currency != null && !currency.equals(c.path("currency").asText())) {
                throw new IOException(facilityId + ": cards disagree on currency");
            }
            currency = c.path("currency").asText();
            LocalDate date = LocalDate.parse(from);
            if (validFrom.put(date, from) != null) {
                throw new IOException(facilityId + ": two cards valid from " + from);
            }
            Set<String> cardKeys = new TreeSet<>();
            for (JsonNode p : c.path("plazas")) {
                String key = p.path("road").asText() + "|" + p.path("name").asText();
                JsonNode rate = p.path(paymentColumn).path(vehicleColumn);
                if (!rate.isNumber()) {
                    throw new IOException(facilityId + ": card " + from + " has no " + paymentColumn + "/"
                            + vehicleColumn + " rate for " + key);
                }
                if (!cardKeys.add(key)) {
                    throw new IOException(facilityId + ": card " + from + " lists " + key + " twice");
                }
                rates.computeIfAbsent(key, k -> new TreeMap<>()).put(date, rate.decimalValue());
            }
            if (!cardKeys.equals(gantryKeys)) {
                Set<String> diff = new TreeSet<>(cardKeys);
                diff.addAll(gantryKeys);
                diff.removeIf(k -> cardKeys.contains(k) && gantryKeys.contains(k));
                throw new IOException(facilityId + ": card " + from
                        + " and the gantry file list different plazas (regenerate the gantries): " + diff);
            }
        }
        if (validFrom.isEmpty()) {
            throw new IOException(facilityId + ": no card");
        }
        if (!validFrom.containsValue(g.path("card_valid_from").asText())) {
            throw new IOException(facilityId + ": gantry file was built against card "
                    + g.path("card_valid_from").asText() + ", which is not loaded");
        }
        GantrySet set = new GantrySet(facilityId, currency, zone, g.path("osm_base").asText(null));
        set.cards.putAll(validFrom);
        for (JsonNode p : g.path("plazas")) {
            String key = p.path("road").asText() + "|" + p.path("name").asText();
            NavigableMap<LocalDate, BigDecimal> rate = Collections.unmodifiableNavigableMap(rates.get(key));
            if (p.path("clusters").isEmpty()) {
                set.unlocated.add(key);
            }
            if (!includeRamps && "ramp".equals(p.path("plaza_type").asText())) {
                set.excludedRamps.add(key);
                continue;
            }
            boolean ramp = "ramp".equals(p.path("plaza_type").asText());
            for (JsonNode cl : p.path("clusters")) {
                double lat = cl.path("lat").asDouble();
                double lon = cl.path("lon").asDouble();
                Envelope e = new Envelope(lon, lon, lat, lat);
                set.extent.expandToInclude(e);
                if (!ramp) {
                    Point point = new Point(facilityId, key, lat, lon, rate, null, null);
                    set.points.add(point);
                    set.index.insert(e, point);
                    continue;
                }
                List<double[][]> rampLines = lines(cl.path("ramp_lines"));
                List<double[][]> mainlineLines = lines(cl.path("mainline_lines"));
                if (rampLines.isEmpty() || mainlineLines.isEmpty()) {
                    set.rampsWithoutGeometry.add(key + " @" + lat + "," + lon);
                    continue;
                }
                Point point = new Point(facilityId, key, lat, lon, rate, rampLines, mainlineLines);
                set.points.add(point);
                Envelope reach = new Envelope(e);
                for (double[][] line : rampLines) {
                    for (double[] v : line) {
                        reach.expandToInclude(v[1], v[0]);
                    }
                }
                double marginLat = RAMP_MARGIN_M / 111320;
                reach.expandBy(marginLat / Math.cos(Math.toRadians(lat)), marginLat);
                set.rampIndex.insert(reach, point);
            }
        }
        set.index.build();
        set.rampIndex.build();
        return set;
    }

    private static List<double[][]> lines(JsonNode node) {
        List<double[][]> result = new ArrayList<>();
        for (JsonNode line : node) {
            double[][] points = new double[line.size()][];
            for (int i = 0; i < line.size(); i++) {
                points[i] = new double[] {line.get(i).get(0).asDouble(), line.get(i).get(1).asDouble()};
            }
            if (points.length >= 2) {
                result.add(points);
            }
        }
        return result;
    }

    /** Mainline toll points near an envelope. */
    @SuppressWarnings("unchecked")
    List<Point> query(Envelope envelope) {
        return index.query(envelope);
    }

    /** Ramp toll points whose clipped ramp could contain the position. */
    @SuppressWarnings("unchecked")
    List<Point> queryRamps(double lat, double lon) {
        return rampIndex.query(new Envelope(lon, lon, lat, lat));
    }

    /** True when the position lies within {@code marginDeg} of this facility's toll points. */
    public boolean near(double lat, double lon, double marginDeg) {
        Envelope e = new Envelope(extent);
        e.expandBy(marginDeg);
        return e.contains(lon, lat);
    }

    public String getFacilityId() {
        return facilityId;
    }

    public String getCurrency() {
        return currency;
    }

    /** The card in effect at an instant (local date in the facility's timezone); null before the first. */
    public String cardAt(Date time) {
        Map.Entry<LocalDate, String> e = cards.floorEntry(localDate(time));
        return e != null ? e.getValue() : null;
    }

    /** Every loaded card's valid_from, oldest first. */
    public List<String> getCards() {
        return List.copyOf(cards.values());
    }

    /** What a passage at {@code time} is charged at the point; null when no card covers that date. */
    public Rate rateAt(Point point, Date time) {
        Map.Entry<LocalDate, BigDecimal> e = point.rates().floorEntry(localDate(time));
        return e != null ? new Rate(e.getValue(), cards.get(e.getKey())) : null;
    }

    private LocalDate localDate(Date time) {
        return time.toInstant().atZone(zone).toLocalDate();
    }

    public String getOsmBase() {
        return osmBase;
    }

    public List<Point> getPoints() {
        return points;
    }

    public List<String> getUnlocated() {
        return unlocated;
    }

    public List<String> getExcludedRamps() {
        return excludedRamps;
    }

    public boolean rampsExcluded() {
        return !excludedRamps.isEmpty();
    }

    /** Ramp plazas that cannot be proven from a trail (no ramp or mainline shape); never charged. */
    public List<String> getRampsWithoutGeometry() {
        return rampsWithoutGeometry;
    }
}
