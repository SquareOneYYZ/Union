package org.traccar.tollpricing;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The Java 407 estimator against {@code price_407_reference.py}, on the same packaged card.
 * The fixture is regenerated by {@code scripts/toll_research/gen_407_parity_cases.py}.
 */
public class DistanceZonedEstimatorTest {

    private static DistanceZonedCard card;

    @BeforeAll
    public static void loadCard() throws Exception {
        card = DistanceZonedCard.loadResource("407-etr-2026-light.json");
    }

    @Test
    public void agreesWithPythonReferenceToTheCent() throws Exception {
        List<String> mismatches = new ArrayList<>();
        int cases = 0;
        try (BufferedReader reader = new BufferedReader(new InputStreamReader(
                getClass().getResourceAsStream("/toll-pricing/407-parity-cases.csv"), StandardCharsets.UTF_8))) {
            reader.readLine();
            String line;
            while ((line = reader.readLine()) != null) {
                String[] f = line.split(",");
                Map<String, Double> zoneKm = new LinkedHashMap<>();
                for (String part : f[3].split(";")) {
                    String[] kv = part.split("=");
                    zoneKm.put(kv[0], Double.parseDouble(kv[1]));
                }
                TollEstimate e = DistanceZonedEstimator.price(
                        card, LocalDateTime.parse(f[0]), f[1], zoneKm, Boolean.parseBoolean(f[2]));
                cases++;
                if (e.getAmount() == null || e.getAmount().compareTo(new BigDecimal(f[6])) != 0
                        || !e.getDayType().equals(f[4]) || !e.getBand().equals(f[5])) {
                    mismatches.add(line + " -> " + e.getDayType() + "," + e.getBand() + "," + e.getAmount());
                }
            }
        }
        assertEquals(400, cases);
        assertTrue(mismatches.isEmpty(), mismatches.size() + " mismatches:\n" + String.join("\n", mismatches));
    }

    @Test
    public void beforeFirstBandUsesPreviousEveningBand() {
        assertEquals("9 p.m.", card.resolveBand(DistanceZonedCard.DAY_WEEKDAY, LocalTime.of(4, 59)));
        assertEquals("5 a.m.", card.resolveBand(DistanceZonedCard.DAY_WEEKDAY, LocalTime.of(5, 0)));
    }

    @Test
    public void unknownZoneIsUnknownNotZero() throws Exception {
        TollEstimate e = DistanceZonedEstimator.price(card, LocalDateTime.parse("2026-03-17T08:12:00"),
                "eastbound", Map.of("Z99", 3.0), false);
        assertNull(e.getAmount());
        assertEquals(TollEstimate.REASON_NO_RATE, e.getReason());
    }

    @Test
    public void feesComeFromTheCard() throws Exception {
        assertEquals(new BigDecimal("1"), card.perTripFee("Trip Toll Charge"));
        assertEquals(new BigDecimal("5.30"), card.perTripFee("Camera Charge"));
        assertNotNull(card.getSourceUrl());
    }
}
